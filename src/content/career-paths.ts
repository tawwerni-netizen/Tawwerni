// Helper Functions
export function getAllCareerPaths(): CareerPath[] {
  return [...CAREER_PATHS].sort((a, b) => a.sortOrder - b.sortOrder);
}

export function getCareerPathBySlug(slug: string): CareerPath | undefined {
  return CAREER_PATHS.find((cp) => cp.slug === slug);
}

export function getCareerPathsByGoal(goal: CareerGoalCategory): CareerPath[] {
  if (goal === "all") return getAllCareerPaths();
  return CAREER_PATHS.filter((cp) => cp.goalCategory === goal).sort((a, b) => a.sortOrder - b.sortOrder);
}

export function getCareerPathsForTrack(trackSlug: string): { careerPath: CareerPath; stage: CareerPathStage; trackRef: CareerPathTrackRef }[] {
  const results: { careerPath: CareerPath; stage: CareerPathStage; trackRef: CareerPathTrackRef }[] = [];

  for (const cp of CAREER_PATHS) {
    for (const stage of cp.stages) {
      const ref = stage.tracks.find((t) => t.trackSlug === trackSlug);
      if (ref) {
        results.push({ careerPath: cp, stage, trackRef: ref });
      }
    }
  }

  return results;
}

export function getTrackDetailsInCareerPath(trackSlug: string): Track100 | undefined {
  return getTrackBySlug(trackSlug);
}
